-- Every setting as one JSON object, numbers as numbers.
CREATE FUNCTION spy.cfg() RETURNS JSONB LANGUAGE sql STABLE
AS $$
    SELECT COALESCE(jsonb_object_agg(name, COALESCE(to_jsonb(value), to_jsonb(text_value))), '{}'::jsonb)
    FROM spy.setting
$$;

-- The time zone setting, or 'UTC' when it is empty or not a known name.
CREATE FUNCTION spy.time_zone() RETURNS TEXT LANGUAGE plpgsql STABLE
AS $$
DECLARE
    tz TEXT;
BEGIN
    SELECT NULLIF(btrim(text_value), '') INTO tz FROM spy.setting WHERE name = 'time_zone';
    IF tz IS NULL THEN
        RETURN 'UTC';
    END IF;
    PERFORM now() AT TIME ZONE tz;
    RETURN tz;
EXCEPTION WHEN invalid_parameter_value THEN
    RETURN 'UTC';
END;
$$;

-- The hours judged, as people read them: "Thu 14h" for one hour, "Thu 13–14h"
-- for more. In the time zone setting. "UTC" is added only when that is UTC.
CREATE FUNCTION spy.slot(p_from TIMESTAMPTZ, p_to TIMESTAMPTZ) RETURNS TEXT LANGUAGE plpgsql STABLE
AS $$
DECLARE
    tz TEXT := spy.time_zone();
BEGIN
    RETURN CASE WHEN p_from = p_to
                THEN to_char(p_to AT TIME ZONE tz, 'Dy HH24"h"')
                ELSE to_char(p_from AT TIME ZONE tz, 'Dy HH24') || '–' || to_char(p_to AT TIME ZONE tz, 'HH24"h"')
           END
           || CASE WHEN tz = 'UTC' THEN ' UTC' ELSE '' END;
END;
$$;

-- Operators: the businesses behind the accounts. The id is kept from the
-- collector, so a code like OP123 means the same operator everywhere.
CREATE TABLE spy.operator (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT GENERATED ALWAYS AS ('OP' || id::text) STORED,
    name TEXT NOT NULL,          -- display name · seller · code
    display_name TEXT,           -- typed by hand, else the oldest running account
    kind TEXT NOT NULL DEFAULT 'direct' CHECK (kind IN ('direct', 'affiliate', 'arbitrage')),
    vertical TEXT,               -- the old market label, when there was one
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Which operator each Tracks account belongs to. An account with no row is
-- not grouped yet, and its sightings count for no operator.
CREATE TABLE spy.account_operator (
    account_id INTEGER PRIMARY KEY,
    operator_id INTEGER NOT NULL REFERENCES spy.operator(id) ON DELETE CASCADE
);
CREATE INDEX account_operator_operator_idx ON spy.account_operator (operator_id);

-- The vertical of each Tracks creative. No row: not classified yet.
CREATE TABLE spy.creative_vertical (
    creative_id INTEGER PRIMARY KEY,
    vertical TEXT,               -- the broad one: health, finance, ... Direction's market
    subvertical TEXT,            -- best guess, also when unsure
    shown_vertical TEXT,         -- what the lists show: a health subvertical's group, any other its own name
    confidence NUMERIC(3, 2) NOT NULL DEFAULT 0,
    unsure BOOLEAN NOT NULL DEFAULT TRUE,  -- below 0.6
    source TEXT,                 -- headline, landing_page, funnel_step, seller, model
    health_from_funnel BOOLEAN NOT NULL DEFAULT FALSE
);

-- When each grouping was last copied, and how much of it.
CREATE TABLE spy.import_mark (
    what TEXT PRIMARY KEY,
    done_at TIMESTAMPTZ NOT NULL,
    copied INTEGER NOT NULL,
    skipped INTEGER NOT NULL     -- rows whose account or creative Tracks has not seen yet
);
