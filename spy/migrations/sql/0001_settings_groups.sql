-- Spy's settings, and the two groupings its numbers are cut by: which
-- operator each account belongs to, and which vertical each creative is in.
-- Ported from the collector's spy schema at e20148c (013, 016, 023, 025, 026,
-- 027, 030, 033). Every id that names an ad, creative, account, publisher or
-- device is Tracks' id (tracks_api); operator ids are Spy's own.
--
-- The grouping itself (operators from sites, clues and account names; the
-- vertical classifier) needs the landing pages Tracks does not collect yet.
-- Until it moves here, spy-numbers import-old copies both groupings from the
-- collector's database, as often as it is run.

-- Tunables. Change a value here, no deploy needed: every refresh reads them.
CREATE TABLE spy.setting (
    name TEXT PRIMARY KEY,
    value NUMERIC,
    text_value TEXT,
    note TEXT NOT NULL,
    CHECK (value IS NOT NULL OR text_value IS NOT NULL)
);

